const escapeXml = value => String(value).replaceAll('&','&amp;').replaceAll('<','&lt;')
  .replaceAll('>','&gt;').replaceAll('"','&quot;').replaceAll("'",'&apos;');

export function createStrategyReferenceXml(strategy) {
  const label = `4.0 STRATEGY REFERENCE — ${strategy.name} (${strategy.model})\n${strategy.rule}\nRESEARCH ONLY · NOT AN EXECUTABLE BOT`;
  return `<xml xmlns="https://developers.google.com/blockly/xml"><block type="text_print" id="senfx-reference-${escapeXml(strategy.id)}" x="24" y="24"><value name="TEXT"><block type="text"><field name="TEXT">${escapeXml(label)}</field></block></value></block></xml>`;
}

export function createStrategyBootstrap(strategies) {
  const catalog = strategies.map(({id,name,model,rule})=>({id,name,model,rule}));
  const source = [
    '(() => {',
    `  const catalog = ${JSON.stringify(catalog).replaceAll('</', '<\\/')};`,
    "  const strategyId = new URLSearchParams(window.location.search).get('senfx_strategy');",
    '  const strategy = catalog.find(item => item.id === strategyId);',
    '  if (!strategy) return;',
    '  let attempts = 0;',
    '  const mount = () => {',
    '    const workspace = window.Blockly && window.Blockly.derivWorkspace;',
    "    const tradeParameters = workspace?.getTopBlocks(false).find(block => block.type === 'trade_definition');",
    '    if (!workspace || !tradeParameters || !window.Blockly.FieldDropdown) {',
    '      if (++attempts < 120) window.setTimeout(mount, 250);',
    '      return;',
    '    }',
    '    if (!window.Blockly.Blocks.tsfx_strategy_rule) {',
    '      window.Blockly.Blocks.tsfx_strategy_rule = {',
    '        init() {',
    "          this.appendDummyInput().appendField('SENFX strategy').appendField(new window.Blockly.FieldDropdown(catalog.map(item => [item.name, item.id])), 'STRATEGY');",
    '          this.setPreviousStatement(true); this.setNextStatement(true); this.setColour(210);',
    "          this.setTooltip('This Blockly strategy selector chooses the existing Trade Scheme FX rule executed by the server-side virtual Demo worker.');",
    '        },',
    '      };',
    '      window.Blockly.JavaScript.javascriptGenerator.forBlock.tsfx_strategy_rule = () => "";',
    '    }',
    '    let strategyBlock = workspace.getAllBlocks(false).find(block => block.type === "tsfx_strategy_rule");',
    '    if (!strategyBlock) {',
    '      strategyBlock = workspace.newBlock("tsfx_strategy_rule");',
    '      strategyBlock.setFieldValue(strategy.id, "STRATEGY");',
    '      strategyBlock.setCommentText(strategy.rule);',
    '      strategyBlock.initSvg(); strategyBlock.render();',
    '      const input = tradeParameters.getInput("INITIALIZATION");',
    '      const stack = tradeParameters.getBlocksInStatement("INITIALIZATION");',
    '      const last = stack[stack.length - 1];',
    '      if (last?.nextConnection?.isConnected()) last.nextConnection.connect(strategyBlock.previousConnection);',
    '      else input?.connection?.connect(strategyBlock.previousConnection);',
    '    } else {',
    '      strategyBlock.setFieldValue(strategy.id, "STRATEGY");',
    '      strategyBlock.setCommentText(strategy.rule);',
    '    }',
    '    let syncAttempts = 0;',
    '    let syncTimer = null;',
    '    let syncBusy = false;',
    '    let preservedStake = null;',
    '    const numericValue = (block, name) => { const child = block?.getInputTargetBlock?.(name); const value = Number(child?.getFieldValue?.("NUM")); return Number.isFinite(value) ? value : null; };',
    '    const setNumericValue = (block, name, value) => { const child = block?.getInputTargetBlock?.(name); if (child && Number.isFinite(value)) child.setFieldValue(String(value), "NUM"); };',
    '    const dropdownOptions = field => { try { return field?.getOptions?.(false) || []; } catch { return []; } };',
    '    const matchingOption = (field, expected) => dropdownOptions(field).find(option => String(option?.[1] ?? "").toLowerCase() === expected || String(option?.[0] ?? "").toLowerCase() === expected || String(option?.[0] ?? "").toLowerCase() === expected + "s");',
    '    const queueSync = () => { if (syncTimer || syncAttempts >= 120) return; syncAttempts += 1; syncTimer = window.setTimeout(() => { syncTimer = null; syncWorkspace(); }, 250); };',
    '    const syncWorkspace = () => {',
    '      if (syncBusy || !workspace || workspace.isDragging?.()) return;',
    '      syncBusy = true;',
    '      try {',
    '        const blocks = workspace.getAllBlocks(false);',
    '        const currentRoot = blocks.find(block => block.type === "trade_definition") || tradeParameters;',
    '        let currentRule = blocks.find(block => block.type === "tsfx_strategy_rule");',
    '        if (!currentRule) {',
    '          currentRule = workspace.newBlock("tsfx_strategy_rule");',
    '          currentRule.setFieldValue(strategy.id, "STRATEGY"); currentRule.setCommentText(strategy.rule); currentRule.initSvg();',
    '          const input = currentRoot?.getInput("INITIALIZATION"); const stack = currentRoot?.getBlocksInStatement("INITIALIZATION") || []; const last = stack[stack.length - 1];',
    '          if (last?.nextConnection?.isConnected()) last.nextConnection.connect(currentRule.previousConnection); else input?.connection?.connect(currentRule.previousConnection);',
    '          currentRule.render();',
    '        } else if (currentRule.getFieldValue("STRATEGY") !== strategy.id) currentRule.setFieldValue(strategy.id, "STRATEGY");',
    '        strategyBlock = currentRule;',
    '        const market = blocks.find(block => block.type === "trade_definition_market");',
    '        const tradeType = blocks.find(block => block.type === "trade_definition_tradetype");',
    '        const categoryField = tradeType?.getField?.("TRADETYPECAT_LIST");',
    '        const typeField = tradeType?.getField?.("TRADETYPE_LIST");',
    '        const genericOptions = blocks.find(block => block.type === "trade_definition_tradeoptions");',
    '        if (genericOptions && preservedStake === null) preservedStake = numericValue(genericOptions, "AMOUNT") ?? 1;',
    '        const multiplierCategory = matchingOption(categoryField, "multiplier");',
    '        if (!market || !categoryField || !typeField || !multiplierCategory) { queueSync(); return; }',
    '        if (categoryField.getValue() !== String(multiplierCategory[1])) { categoryField.setValue(String(multiplierCategory[1])); queueSync(); return; }',
    '        const multiplierType = matchingOption(typeField, "multiplier");',
    '        if (!multiplierType) { queueSync(); return; }',
    '        if (typeField.getValue() !== String(multiplierType[1])) { typeField.setValue(String(multiplierType[1])); queueSync(); return; }',
    '        const freshBlocks = workspace.getAllBlocks(false);',
    '        const multiplierBlock = freshBlocks.find(block => block.type === "trade_definition_multiplier");',
    '        if (!multiplierBlock) { queueSync(); return; }',
    '        const stake = Math.max(1, preservedStake ?? numericValue(multiplierBlock, "AMOUNT") ?? 1);',
    '        if (numericValue(multiplierBlock, "AMOUNT") !== stake) setNumericValue(multiplierBlock, "AMOUNT", stake);',
    '        const multiplierField = multiplierBlock.getField?.("MULTIPLIERTYPE_LIST");',
    '        const multiplierOptions = dropdownOptions(multiplierField);',
    '        const multiplierValue = Number(multiplierField?.getValue?.());',
    '        if (!(multiplierValue > 0)) { const first = multiplierOptions.find(option => Number(option?.[1]) > 0); if (first) multiplierField.setValue(String(first[1])); else { queueSync(); return; } }',
    '        for (const type of ["multiplier_take_profit", "multiplier_stop_loss"]) {',
    '          const riskBlock = multiplierBlock.getChildByType?.(type);',
    '          if (!riskBlock) { queueSync(); return; }',
    '          const risk = numericValue(riskBlock, "AMOUNT");',
    '          if (!(risk > 0)) setNumericValue(riskBlock, "AMOUNT", stake);',
    '          riskBlock.setDisabled?.(false);',
    '        }',
    '        preservedStake = null; syncAttempts = 0;',
    '        const note = strategy.name + " — strategy rule\\n" + strategy.rule + "\\nThis rule runs through the Trade Scheme FX Demo worker.";',
    '        if (currentRoot?.getCommentText?.() !== note) currentRoot?.setCommentText(note);',
    '        workspace.__senfxStrategyReference = strategy.id; workspace.__tsfxMultiplierWorkspaceReady = true; workspace.render();',
    '      } catch (error) { console.warn("Trade Scheme Blockly workspace sync pending", error); queueSync(); }',
    '      finally { syncBusy = false; }',
    '    };',
    '    if (!workspace.__tsfxStrategyListener) {',
    '      workspace.__tsfxStrategyListener = true;',
    '      workspace.addChangeListener(() => { if (syncBusy) return; syncAttempts = 0; queueSync(); });',
    '    }',
    '    syncWorkspace();',
    '  };',
    '  mount();',
    '})();',
  ].join('\n');
  return `<script>${source}</script>`;
}
